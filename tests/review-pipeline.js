"use strict";
const assert = require("assert");
const fs = require("fs");
const Pgn = require("../assets/web/pgn.js");
assert.ok(fs.existsSync(require("path").join(__dirname,"../assets/web/review-pipeline.js")), "review pipeline exists");
const Pipeline = require("../assets/web/review-pipeline.js");
const Classify = require("../assets/web/move-classification.js");
async function main() {
  const rows = Pgn.parse("1. e4 e5 2. Nf3 *").games[0].moves;
  rows[0].book = rows[1].book = true;
  const calls = [], positions = [], progress = [];
  const search = async opts => {
    calls.push(opts);
    return {bestmove: "a2a3",lines:[{move:"a2a3",eval:{type:"cp",value:0},depth:opts.depth}]};
  };
  const opts = {search,depth:14,onPosition:(i,r)=>positions.push(i),onProgress:(d,t)=>progress.push([d,t])};
  const first = await Pipeline.run(rows,opts);
  assert.strictEqual(calls.length,2,"only nonbook move boundaries need searches");
  assert.ok(first[2] && first[3]);
  assert.deepStrictEqual(progress[progress.length-1],[4,4]);
  assert.ok(progress.slice(0,-1).every(p=>p[0]<p[1]),"100% is reported only when refinements finish");
  Classify.classifyRow(rows[0],0,first);
  assert.strictEqual(rows[0].loss,0,"book accuracy counts without engine data");
  await Pipeline.run(rows,opts);
  assert.strictEqual(calls.length,2,"identical cached policy and FEN reused");
  await Pipeline.run(rows,Object.assign({},opts,{depth:18}));
  assert.ok(calls.length>2,"deep must not reuse fast results");
  assert.strictEqual(await Pipeline.run(rows,{search,isCancelled:()=>true}),null);
  let cancelled = false, published = 0;
  const interrupted = await Pipeline.run(rows,{search:async opts=>{cancelled=true;return search(opts);},isCancelled:()=>cancelled,onPosition:()=>published++});
  assert.strictEqual(interrupted,null);
  assert.strictEqual(published,0,"cancelled search results must not be published");
  const mate = Pgn.parse("1. f3 e5 2. g4 Qh4#").games[0].moves;
  const results = await Pipeline.run(mate,{search,depth:14});
  assert.strictEqual(results[4].lines[0].eval.type,"mate");
  assert.strictEqual(results[4].lines[0].eval.value,0);
  const drawRows = Pgn.parse('[FEN "4k3/8/8/8/8/8/5b2/4K3 w - - 0 1"]\n\n1. Kxf2 *').games[0].moves;
  const drawn = await Pipeline.run(drawRows,{search,depth:14});
  assert.strictEqual(drawn[1].terminal,"draw");
  assert.deepStrictEqual(drawn[1].lines[0].eval,{type:"cp",value:0});
  const sacrificeRows = Pgn.parse("1. e4 *").games[0].moves;
  sacrificeRows[0].sacrifice = 2;
  const sacrificeCalls = [];
  await Pipeline.run(sacrificeRows, {depth:14,search:async function(opts){sacrificeCalls.push(opts);return {bestmove:"d2d4",lines:[{move:"d2d4",depth:opts.depth,eval:{type:"cp",value:30}}]};}});
  assert.strictEqual(sacrificeCalls.length,4,"жертва вне MultiPV требует проверки позиции после хода");
  assert.strictEqual(sacrificeCalls[3].fen,sacrificeRows[0].fenAfter);
  assert.strictEqual(sacrificeCalls[3].depth,18);
  const repeated=Pgn.parse("1. Nf3 Nf6 2. Ng1 Ng8 3. Nf3 Nf6 4. Ng1 Ng8 5. Nf3 Nf6 6. Ng1 Ng8 7. Nf3 Nf6 8. Ng1 Ng8 *").games[0].moves;
  const repeatedResult=await Pipeline.run(repeated,{search,depth:14});
  assert.strictEqual(repeatedResult[16].terminal,"draw","pipeline respects fivefold repetition history");
  console.log("review pipeline ok");
}
main().catch(e=>{console.error(e);process.exitCode=1;});
