const assert = require('assert');
const G = require('../assets/web/game-session.js');
let now = 1000;
const c = G.createClock({baseMs:60000, incrementMs:2000, now:()=>now});
c.start('w'); now += 3000;
assert.strictEqual(c.remaining('w'),57000);
assert.strictEqual(c.move('b'),true);
assert.strictEqual(c.remaining('w'),59000);
now += 4000; c.pause(); now += 100000;
assert.strictEqual(c.remaining('b'),56000);
c.resume(); now += 56001;
assert.strictEqual(c.snapshot().flag,'b');
assert.strictEqual(c.move('w'),false);
assert.strictEqual(c.remaining('b'),0);
c.resume(); assert.strictEqual(c.snapshot().running,false);
c.restore({w:12000,b:34000,turn:'w',flag:null});
assert.strictEqual(c.snapshot().running,true);
now+=1000;assert.strictEqual(c.remaining('w'),11000);
const u=G.createClock({baseMs:0, now:()=>now});u.start('w');now+=1000000;
assert.strictEqual(u.snapshot().flag,null);
G.RATINGS.forEach(elo=>{const p=G.profile(elo);assert.strictEqual(p.elo,elo);assert.ok(p.skill>=0 && p.skill<=20);});
assert.strictEqual(G.profile(4000).engineElo,0);
assert.strictEqual(G.estimate(90,5,1200),null);
assert.ok(G.estimate(95,20,1800)>G.estimate(50,20,1800));
assert.strictEqual(G.timeoutWinner(['K','.','.','k','q'],'b'),null);
assert.strictEqual(G.timeoutWinner(['K','R','.','k','.'],'b'),'w');
assert.strictEqual(G.timeoutWinner(['K','Q','.','k','.'],'w'),null);
assert.strictEqual(G.timeoutWinner(['K','.','.','k','p'],'w'),'b');
console.log('ok game clocks, rating profiles, limited performance estimate');
